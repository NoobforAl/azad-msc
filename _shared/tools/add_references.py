"""Add a "Go deeper" REFERENCES slide to every lesson deck, from _shared/resources/awesome-os.json.

Usage:
  python _shared/tools/add_references.py            # (re)generate the slides + RESOURCES.en.md / RESOURCES.fa.md
  python _shared/tools/add_references.py --check    # only verify that every link in the data file is live

The slide sits after SUMMARY and is replaced (not duplicated) on every run. Edit the JSON, never the generated
slide. Every link in the JSON was taken from the two GitHub "awesome-os" lists named in it and checked live
(date in the file); run --check again before a presentation.
"""

import argparse
import concurrent.futures as cf
import html
import json
import pathlib
import re
import ssl
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "_shared" / "resources" / "awesome-os.json"
COURSE = ROOT / "term-1" / "advanced-operating-systems"
START, END = "<!-- REFERENCES:start", "<!-- REFERENCES:end -->"

T = {  # slide text
    "en": {
        "eyebrow": "Go deeper",
        "title": "Read more, picked from the GitHub “awesome-os” lists",
        "src": "Lists",
        "checked": "links checked",
        "say": "These are the best next reads after this module. They come from two GitHub “awesome-os” lists and every link was opened and checked on {d}. You do not need all of them.",
        "key": "Start with the first item. The papers and conference pages are for the curious.",
        "dir": "ltr",
    },
    "fa": {
        "eyebrow": "ادامهٔ مطالعه",
        "title": 'برای مطالعهٔ بیشتر، منتخب از فهرست‌های <bdi dir="ltr">awesome-os</bdi>',
        "src": "فهرست‌ها",
        "checked": "لینک‌ها بررسی شده",
        "say": "این‌ها بهترین منابع برای ادامه پس از این ماژول هستند. از دو فهرست «awesome-os» در GitHub انتخاب شده‌اند و همهٔ لینک‌ها در تاریخ {d} باز و بررسی شده‌اند. لازم نیست همه را بخوانید.",
        "key": "از مورد اول شروع کنید. مقاله‌ها و صفحهٔ کنفرانس‌ها برای کنجکاوهاست.",
        "dir": "rtl",
    },
}


def load():
    return json.loads(DATA.read_text(encoding="utf-8"))


def entries(data, module):
    out = []
    for e in data["modules"][module]:
        e = {"id": e} if isinstance(e, str) else dict(e)
        it = dict(data["items"][e["id"]])
        it["id"] = e["id"]
        for lang in ("en", "fa"):
            it[lang] = e.get(lang, it[lang])
        out.append(it)
    return out


# One English term, a call such as read(fd, buf), or words like "page cache" -- but never across a parenthesis that belongs to the
# Persian sentence, so "روی aos-lab (Linux 6.18.63)" gives two separate runs.
_TOKEN = r"(?:['’][0-9]{2}|[/~]?[A-Za-z0-9_][A-Za-z0-9_.+#:%@=/~-]*(?:\([A-Za-z0-9_*&.,:+/ \-\[\]]*\))*)"
_PAREN = r"\([A-Za-z0-9_*&.,:+/ \-\[\]]*\)"  # an all-English parenthetical that follows an English term
LATIN = re.compile(_TOKEN + "(?: " + _TOKEN + "| " + _PAREN + ")*")


def esc(text, lang):
    """HTML-escape; in Farsi, isolate each English run so punctuation and quotes do not jump around (bidi)."""
    text = text.replace("‏", "")
    if lang != "fa":
        return html.escape(text)
    out, last = [], 0
    for m in LATIN.finditer(text):
        tail = re.search(r"[.,:;=]+$", m.group(0))
        run = m.group(0)[: -len(tail.group(0))] if tail else m.group(0)
        if not re.search(r"[A-Za-z0-9]", run):
            continue
        out.append(html.escape(text[last : m.start()]))
        out.append('<bdi dir="ltr">' + html.escape(run) + "</bdi>")
        last = m.start() + len(run)
    out.append(html.escape(text[last:]))
    return "".join(out)


def short_url(u):
    return re.sub(r"^https?://(www\.)?", "", u).rstrip("/")[:64]


def slide_html(data, module, lang, number):
    t = T[lang]
    kinds = data["kinds"]
    lis = []
    for i, it in enumerate(entries(data, module), 1):
        lis.append(
            f'    <li class="in d{min(i, 5)}"><span class="pill">{html.escape(kinds[it["kind"]][lang])}</span> '
            f'<a href="{html.escape(it["url"])}"><b>{html.escape(it["title"])}</b></a>'
            f'<span class="why">{esc(it[lang], lang)}</span>'
            f'<span class="url ltr">{html.escape(short_url(it["url"]))}</span></li>'
        )
    lists = " · ".join(x["id"] for x in data["lists"] if x["use"] == "main")
    notes = (
        f"SAY (EN): {T['en']['say'].format(d=data['checked'])}\n"
        f"SAY (FA): {T['fa']['say'].format(d=data['checked'])}\n"
        f"KEY POINT: {T['en']['key']}\nEXAMPLE: —\nPITFALL: Some links are PDFs; open them before class if the room has no internet.\nTIME: 30"
    )
    return (
        f"{START} (generated by _shared/tools/add_references.py from _shared/resources/awesome-os.json; do not edit by hand) -->\n"
        f"<!-- {number:02d} REFERENCES -->\n"
        f'<section class="layout-refs">\n'
        f'  <span class="eyebrow in-f">{t["eyebrow"]}</span>\n'
        f'  <h2 class="in">{t["title"]}</h2>\n'
        f'  <ul class="refs">\n' + "\n".join(lis) + "\n  </ul>\n"
        f'  <p class="caption src">{t["src"]}: <span class="ltr">{lists}</span> · {t["checked"]} <bdi dir="ltr">{data["checked"]}</bdi></p>\n'
        f'  <aside class="notes">\n{notes}\n  </aside>\n</section>\n{END}\n'
    )


def patch_deck(path, data, module, lang):
    s = path.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s.replace("\r\n", "\n")
    s = re.sub(
        re.escape(START) + r".*?" + re.escape(END) + r"\n?\n?", "", s, flags=re.S
    )  # drop the old generated slide
    last = s.rfind("</section>")
    if last < 0:
        raise SystemExit(f"no slides in {path}")
    number = len(re.findall(r"<section\b", s)) + 1
    insert_at = last + len("</section>")
    s = s[:insert_at] + "\n\n" + slide_html(data, module, lang, number).rstrip("\n") + s[insert_at:]
    path.write_bytes(s.replace("\n", nl).encode("utf-8"))


def write_resources(data):
    """RESOURCES.{en,fa}.md: the same picks as the slides, plus which lists were used and why."""
    for lang in ("en", "fa"):
        fa = lang == "fa"
        L = [
            ("# منابع بیشتر برای مطالعه" if fa else "# Further reading"),
            "",
            (
                f"منتخب از فهرست‌های «awesome-os» در GitHub. همهٔ لینک‌ها در {data['checked']} باز و بررسی شده‌اند "
                "(`python _shared/tools/add_references.py --check` دوباره بررسی می‌کند). همین موارد در آخرین اسلاید هر درس هم آمده‌اند."
                if fa
                else f"Picked from GitHub “awesome-os” lists. Every link was opened and checked on {data['checked']} "
                "(`python _shared/tools/add_references.py --check` re-checks them). The same picks are the last slide of each lesson deck."
            ),
            "",
        ]
        for mod in data["modules"]:
            L += [f"## {mod}", ""]
            for it in entries(data, mod):
                L.append(f"- **[{it['title']}]({it['url']})** ({data['kinds'][it['kind']][lang]}): {it[lang]}")
            L.append("")
        L += [
            ("## فهرست‌هایی که بررسی شد" if fa else "## Lists that were reviewed"),
            "",
            ("| فهرست | استفاده | دلیل |" if fa else "| List | Used | Why |"),
            "|---|---|---|",
        ]
        for entry in data["lists"]:
            used = ("بله" if entry["use"] == "main" else "خیر") if fa else ("yes" if entry["use"] == "main" else "no")
            L.append(f"| [{entry['id']}]({entry['url']}) | {used} | {entry[lang]} |")
        L += [
            "",
            (
                "یادداشت: لینک مقالهٔ «The UNIX Time-Sharing System» در penberg/awesome-os (dsf.berkeley.edu) دیگر کار نمی‌کند، پس نیامده است."
                if fa
                else "Note: the link to “The UNIX Time-Sharing System” in penberg/awesome-os (dsf.berkeley.edu) no longer resolves, so it is not included."
            ),
            "",
        ]
        (COURSE / f"RESOURCES.{lang}.md").write_text("\n".join(L), encoding="utf-8")


def check_links(data):
    def probe(item):
        iid, it = item
        req = urllib.request.Request(
            it["url"], headers={"User-Agent": "Mozilla/5.0 (link check)", "Range": "bytes=0-2048"}
        )
        try:
            with urllib.request.urlopen(req, timeout=30, context=ssl.create_default_context()) as r:
                return iid, True, f"{r.status} {r.headers.get('Content-Type', '').split(';')[0]}"
        except Exception as e:  # noqa: BLE001 - report every failure
            return iid, False, f"{type(e).__name__}: {str(e)[:70]}"

    with cf.ThreadPoolExecutor(8) as ex:
        res = list(ex.map(probe, data["items"].items()))
    bad = 0
    for iid, ok, info in res:
        if not ok:
            bad += 1
            print(f"DEAD {iid:<14} {data['items'][iid]['url']}  ({info})")
    print(f"{len(res) - bad}/{len(res)} links live")
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="only verify links")
    a = ap.parse_args()
    data = load()
    for mod, ids in data["modules"].items():
        for e in ids:
            if (e if isinstance(e, str) else e["id"]) not in data["items"]:
                sys.exit(f"{mod}: unknown item {e!r}")
    if a.check:
        sys.exit(1 if check_links(data) else 0)
    n = 0
    for mod in data["modules"]:
        for lang in ("en", "fa"):
            deck = COURSE / mod / "slides" / f"lesson.{lang}.html"
            if not deck.is_file():
                print(f"skip (no deck): {deck.relative_to(ROOT).as_posix()}")
                continue
            patch_deck(deck, data, mod, lang)
            n += 1
    write_resources(data)
    print(f"{n} lesson decks updated; RESOURCES.en.md / RESOURCES.fa.md written")


if __name__ == "__main__":
    main()
